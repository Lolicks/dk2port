#!/usr/bin/env python3
"""Render STATUS.md from status.json plus optional CI build metadata."""
import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATE = {"done": "DONE", "partial": "PARTIAL", "missing": "MISSING",
         "unverified": "UNVERIFIED"}


def main(argv=None):
    argv = argv or sys.argv
    src = argv[1] if len(argv) > 1 else os.path.join(HERE, "status.json")
    dst = argv[2] if len(argv) > 2 else os.path.join(HERE, "STATUS.md")
    with open(src, encoding="utf-8") as fh:
        data = json.load(fh)

    run = os.environ.get("DK2_RUN_URL") or data["build"]["last_successful_run"]
    ipa = os.environ.get("DK2_IPA_SIZE") or str(data["build"]["ipa_size_bytes"])
    signed = data["build"]["signed"]
    device_ok = data["verification"]["device_tested"]

    lines = [
        "# DK2Port — STATUS (auto-generated)",
        "",
        f"**Updated:** {data['updated']}  ",
        f"**Verdict:** {data['verdict']}",
        "",
        "## Build & distribution",
        "",
        f"- Last successful CI run: {run}",
        f"- IPA size: {int(ipa):,} bytes ({int(ipa)/1048576:.1f} MiB)",
        f"- Permanent download: {data['build']['release']} (asset `{data['build']['artifact']}`)",
        f"- Signed: **{'YES' if signed else 'NO'}** — {data['build']['signing_note']}",
        f"- Verified on {data['verification']['target_device']}: **{'YES' if device_ok else 'NO'}** — "
        f"{data['verification']['note']}",
        "",
        "## Subsystem status",
        "",
        "| Subsystem | Status | Evidence / note |",
        "|---|---|---|",
    ]
    order = {"done": 0, "partial": 1, "unverified": 2, "missing": 3}
    for item in sorted(data["subsystems"], key=lambda x: order.get(x["state"], 9)):
        lines.append("| {} | {} | {} |".format(
            item["name"], STATE.get(item["state"], item["state"]),
            item.get("evidence", "").replace("|", "/")))

    counts = {}
    for item in data["subsystems"]:
        counts[item["state"]] = counts.get(item["state"], 0) + 1
    lines += [
        "",
        "## Summary",
        "",
        "  ".join(f"{STATE.get(k, k)}: {v}" for k, v in sorted(
            counts.items(), key=lambda kv: order.get(kv[0], 9))),
        "",
        "This file is regenerated by `tools/gen_status.py` on every CI build. "
        "Do not edit `STATUS.md` manually — update `status.json` instead.",
        "",
    ]
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {dst} ({len(data['subsystems'])} subsystems)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
