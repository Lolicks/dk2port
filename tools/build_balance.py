#!/usr/bin/env python3
"""Build docs/balance.json + engine/Balance.generated.hpp from the shipped manuals.

Every number here is quoted from manual.pdf / reference_card.pdf supplied with
the original game; nothing is invented.  Values that the manual does not state
remain null/unknown.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DOCS = os.path.join(ROOT, "docs")
ENGINE = os.path.join(ROOT, "engine")

ROOM_COSTS = {
    "Dungeon Heart": None, "Treasury": 200, "Lair": 300, "Hatchery": 300,
    "Training Room": 500, "Combat Pit": 750, "Temple": 750, "Workshop": 600,
    "Casino": 2000, "Graveyard": 2000, "Portal": 750,
    "Torture Chamber": 1500, "Prison": 750, "Library": 1500,
    "Guard Room": 600, "Wooden Bridge": 200, "Stone Bridge": 500,
}

# From reference_card.pdf, page "ROOM / CREATURE / CREATURE SPELLS".
CREATURES = [
    ("Imp", ["Dungeon Heart"], []),
    ("Firefly", ["Lair"], ["Whirlpool"]),
    ("Goblin", ["Lair"], []),
    ("Warlock", ["Lair", "Library"], ["Fireball", "Heal Creature", "Firebomb"]),
    ("Salamander", ["Lair", "Training Room"], ["Spit", "Fireball"]),
    ("Rogue", ["Lair", "Treasury", "Casino"], ["Invisible"]),
    ("Troll", ["Lair", "Workshop"], []),
    ("Bile Demon", ["Lair", "Workshop", "Hatchery(5x5)"], ["Gas Cloud", "Gas Missile"]),
    ("Dark Elf", ["Lair", "Guard Room"], ["Arrow", "Knives", "Guided Bolt"]),
    ("Skeleton", ["Prison*"], []),
    ("Mistress", ["Lair", "Torture Chamber"], ["Lightning", "Freeze", "Hailstorm"]),
    ("Vampire", ["Graveyard**"], ["Slow", "Drain", "Raise Dead"]),
    ("Black Knight", ["Lair", "Combat Pit"], []),
    ("Dark Angel", ["Lair", "Temple"], ["Disruption", "Hail Storm", "Skeleton Army"]),
]


def main():
    balance = {
        "source": ["manual.pdf", "reference_card.pdf"],
        "note": "Values quoted from the shipped documentation. null = not documented.",
        "room_costs": ROOM_COSTS,
        "creature_requirements": [
            {"name": n, "rooms": r, "spells": s} for n, r, s in CREATURES
        ],
        "creature_spell_notes": {
            "Imp": "Haste Self, Teleport (card column preceding Imp)",
            "*": "requires death of a prisoner",
            "**": "requires bodies to rise from the dead",
        },
    }
    with open(os.path.join(DOCS, "balance.json"), "w") as fh:
        json.dump(balance, fh, indent=2, ensure_ascii=False)

    entries = []
    for name, cost in ROOM_COSTS.items():
        entries.append('    {"%s", %d},' % (name, cost if cost is not None else -1))
    header = """// Generated by tools/build_balance.py from the shipped manuals. Do not edit.
#pragma once
#include <cstddef>
struct DK2RoomCost { const char* name; int gold; };
static const DK2RoomCost kDK2RoomCosts[] = {
%s
};
static const size_t kDK2RoomCostCount = sizeof(kDK2RoomCosts) / sizeof(kDK2RoomCosts[0]);
""" % "\n".join(entries)
    with open(os.path.join(ENGINE, "Balance.generated.hpp"), "w") as fh:
        fh.write(header)
    print("wrote balance.json (%d rooms, %d creatures)" % (len(ROOM_COSTS), len(CREATURES)))


if __name__ == "__main__":
    main()
