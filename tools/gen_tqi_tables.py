#!/usr/bin/env python3
"""Mechanically transcribe the static tables in TgqFrame.java into C.

This script exists so the C decoder's VLC/dequant tables cannot drift from the
Java reference by manual copy/paste. It reads only the Java source and writes
one C header. No Java code is executed and no target bytes are involved.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JAVA = ROOT / "research/OpenKeeper/src/main/java/toniarts/openkeeper/video/tgq/TgqFrame.java"
OUT = ROOT / "decoder/tqi/tqi_tables.h"


def array_body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*=\s*\{", text)
    if not m:
        raise SystemExit("table not found: " + name)
    start = m.end() - 1
    depth = 0
    for i in range(start, len(text)):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise SystemExit("unbalanced braces: " + name)


def strip_comments(s):
    s = re.sub(r"//[^\n]*", "", s)
    s = re.sub(r"/\*.*?\*/", "", s, flags=re.S)
    return s


def named_constant(name):
    m = re.search(r"\b" + re.escape(name) + r"\s*=\s*(-?\d+)\s*;", JAVA_SOURCE)
    if not m:
        raise SystemExit("constant not found: " + name)
    return int(m.group(1))


def flat(name):
    nums = [int(v, 0) for v in re.findall(r"-?\d+", strip_comments(array_body(JAVA_SOURCE, name)))]
    return nums


def rows(name):
    body = strip_comments(array_body(JAVA_SOURCE, name))
    # DCT_COEFF uses two named sentinels; resolve them from their declarations.
    body = body.replace("EOB", str(named_constant("EOB")))
    body = body.replace("DCT_ESCAPE", str(named_constant("DCT_ESCAPE")))
    out = []
    for row in re.findall(r"\{([^{}]*)\}", body):
        out.append([int(v, 0) for v in re.findall(r"-?\d+", row)])
    return out


def emit_flat(lines, name, ctype, values, per_line=8):
    lines.append("static const %s %s[%d] = {" % (ctype, name, len(values)))
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        lines.append("    " + ", ".join(str(v) for v in chunk) + ",")
    lines.append("};")
    lines.append("")


def emit_rows(lines, name, ctype, values):
    lines.append("static const %s %s[%d][%d] = {" % (ctype, name, len(values), len(values[0])))
    for row in values:
        lines.append("    { " + ", ".join(str(v) for v in row) + " },")
    lines.append("};")
    lines.append("")


JAVA_SOURCE = JAVA.read_text(encoding="utf-8")

scan = flat("SCAN_TABLE")
base = flat("BASE_TABLE")
base2 = flat("BASE_TABLE2")
dcl = rows("DC_LUMINANCE_VLC")
dcc = rows("DC_CROMINANCE_VLC")
dct = rows("DCT_COEFF")

assert len(scan) == 64, len(scan)
assert len(base) == 64, len(base)
assert len(base2) == 64, len(base2)
assert len(dcl) == 19 and all(len(r) == 3 for r in dcl)
assert len(dcc) == 19 and all(len(r) == 3 for r in dcc)
assert len(dct) == 227 and all(len(r) == 4 for r in dct), len(dct)

lines = [
    "/* Generated by port/tools/gen_tqi_tables.py from",
    " * port/research/OpenKeeper/src/main/java/toniarts/openkeeper/video/tgq/TgqFrame.java.",
    " * Do not edit by hand; regenerate with: python3 port/tools/gen_tqi_tables.py",
    " * Values are transcribed mechanically; no Java code is executed. */",
    "#ifndef DK2_TQI_TABLES_H",
    "#define DK2_TQI_TABLES_H",
    "",
    "#include <stdint.h>",
    "",
]
emit_flat(lines, "TQI_SCAN_TABLE", "int16_t", scan)
emit_flat(lines, "TQI_BASE_TABLE", "int32_t", base)
emit_flat(lines, "TQI_BASE_TABLE2", "int32_t", base2)
emit_rows(lines, "TQI_DC_LUMINANCE_VLC", "int16_t", dcl)
emit_rows(lines, "TQI_DC_CHROMINANCE_VLC", "int16_t", dcc)
emit_rows(lines, "TQI_DCT_COEFF", "int16_t", dct)
lines += ["#endif", ""]

OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote %s (%d lines)" % (OUT, len(lines)))
print("scan=%d base=%d base2=%d dc_luma=%d dc_chroma=%d dct=%d" %
      (len(scan), len(base), len(base2), len(dcl), len(dcc), len(dct)))
