#!/usr/bin/env python3
"""Generate C++ tables from the recovered original game data.

Inputs:  docs/stats.json, docs/triggers.json, docs/game_data.json
Outputs: engine/CreatureStats.generated.hpp, engine/MissionRules.generated.hpp
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
DOCS = os.path.join(PORT, "docs")
ENGINE = os.path.join(PORT, "engine")


def val(entry, key, default=0):
    if not isinstance(entry, dict):
        return default
    item = entry.get(key)
    if isinstance(item, dict):
        return item.get("value", default)
    return item if item is not None else default


def fnum(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) + "f" if isinstance(v, float) else str(v)
    return "0"


def gen_creatures(stats):
    rows = []
    for c in stats["creatures"]:
        s = c.get("stats", {})
        def sane(key, default, hi):
            v = float(val(s, key, default))
            return v if 0.0 <= v <= hi else float(default)
        row = (
            '    {"%s", %d, %.6ff, %.6ff, %.6ff, %.6ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %d},'
            % (
                c["name"].replace('"', ''),
                int(val(s, "hp", 100)),
                float(val(s, "speed", 1.0)),
                float(val(s, "run_speed", val(s, "speed", 1.0))),
                float(val(s, "melee_damage", 10)),
                float(val(s, "melee_recharge", 1.0)),
                sane("fear", 5, 1000),
                sane("threat", 2, 1000),
                sane("melee_range", 1.0, 100),
                sane("distance_can_see", 8.0, 100),
                sane("pay", 0, 100000),
                sane("unhappy_threshold", 50, 100),
                int(val(s, "max_gold_held", 0)),
            )
        )
        rows.append(row)
    return """// Generated by tools/gen_engine_data.py from shipped game data. Do not edit.
#pragma once
struct DK2CreatureStat {
    const char *name;
    int hp;
    float speed;
    float run_speed;
    float melee_damage;
    float melee_recharge;
    float fear;
    float threat;
    float melee_range;
    float sight_range;
    float pay;
    float unhappy_threshold;
    int max_gold_held;
};
static const DK2CreatureStat kDK2CreatureStats[] = {
%s
};
static const unsigned kDK2CreatureStatCount =
    sizeof(kDK2CreatureStats) / sizeof(kDK2CreatureStats[0]);
""" % "\n".join(rows)


def gen_missions(triggers):
    out = []
    for m in triggers["maps"]:
        wl = m.get("win_lose", {})
        requirements = []
        for finding in wl.get("findings", []):
            if finding.get("action") != "WIN_GAME":
                continue
            for cond in finding.get("ancestor_conditions", []):
                t = cond.get("type_name", "")
                p = cond.get("params", {})
                if t.startswith("PLAYER_GOLD"):
                    requirements.append(("gold", float(p.get("value", 0))))
                elif t.startswith("PLAYER_CREATURES"):
                    requirements.append(("creatures", float(p.get("value", 0))))
                elif t.startswith("PLAYER_ROOMS"):
                    requirements.append(("rooms", float(p.get("value", 0))))
                elif t.startswith("TIMER"):
                    requirements.append(("time", float(p.get("value", 0))))
                elif t.startswith("PLAYER_KILLED"):
                    requirements.append(("enemy_killed", 1.0))
        g = max([v for k, v in requirements if k == "gold"] or [0])
        c = max([v for k, v in requirements if k == "creatures"] or [0])
        r = max([v for k, v in requirements if k == "rooms"] or [0])
        t = max([v for k, v in requirements if k == "time"] or [0])
        ek = 1 if any(k == "enemy_killed" for k, _ in requirements) else 0
        out.append('    {"%s", %.1ff, %.1ff, %.1ff, %.1ff, %d},' %
                   (m["name"].replace('"', ''), g, c, r, t, ek))
    return """// Generated by tools/gen_engine_data.py from recovered mission triggers.
#pragma once
struct DK2MissionRule {
    const char *map;
    float required_gold;
    float required_creatures;
    float required_rooms;
    float min_time;
    int enemy_must_die;
};
static const DK2MissionRule kDK2MissionRules[] = {
%s
};
static const unsigned kDK2MissionRuleCount =
    sizeof(kDK2MissionRules) / sizeof(kDK2MissionRules[0]);
""" % "\n".join(out)



def gen_trigger_data(triggers):
    out = []
    for m in triggers["maps"]:
        nodes = []
        for n in m.get("nodes", []):
            params = n.get("params", {}) or {}
            value = params.get("value", 0) if isinstance(params, dict) else 0
            try:
                value = float(value)
            except (TypeError, ValueError):
                value = 0.0
            try:
                fid = int(params.get("flag_id", params.get("timer_id", 0)) or 0)
            except (TypeError, ValueError):
                fid = 0
            nodes.append(
                '        {%d,%d,%d,%.1ff,%d,%d,%d,%d},' % (
                    int(n.get("id", 0)),
                    1 if n.get("kind") == "action" else 0,
                    int(n.get("type_id", 0)),
                    value,
                    int(n.get("next_id", 0)),
                    int(n.get("child_id", 0)),
                    int(params.get("player_id", 0) or 0),
                    fid,
                )
            )
        out.append('    {"%s", %d,' %
                   (m["name"].replace('"', ''), len(nodes)))
        out.append('     (const DK2TriggerNode[]){' + "\n".join(nodes) + '}},')
    return """// Generated by tools/gen_engine_data.py from recovered mission triggers.
// Chain semantics are a reconstruction: next = AND-chain, child = branch/action.
#pragma once
struct DK2TriggerNode {
    unsigned id;
    unsigned char is_action;
    unsigned char type;
    float value;
    unsigned next;
    unsigned child;
    unsigned player;
    unsigned id_param;   // flag_id / timer_id / action-point id
};
struct DK2MissionTriggers {
    const char *map;
    unsigned count;
    const DK2TriggerNode *nodes;
};
static const DK2MissionTriggers kDK2MissionTriggers[] = {
%s
};
static const unsigned kDK2MissionTriggerCount =
    sizeof(kDK2MissionTriggers) / sizeof(kDK2MissionTriggers[0]);
""" % "\n".join(out)


def gen_spells(stats):
    rows = []
    for sp in stats["keeper_spells"]:
        st = sp.get("stats", {})
        rows.append('    {"%s", %d, %d, %.1ff, %.1ff, %d, %d},' % (
            sp["name"].replace('"', ''),
            int(val(st, "keeper_spell_id", 0)),
            int(val(st, "mana_cost", 0)),
            float(val(st, "research_time", 0)),
            float(val(st, "recharge_time", 0)),
            int(val(st, "cast_rule", 0)),
            int(val(st, "target_rule", 0)),
        ))
    return """// Generated by tools/gen_engine_data.py from KeeperSpells.kwd.
#pragma once
struct DK2SpellData {
    const char *name;
    int id;
    int mana_cost;
    float research_time;
    float recharge_time;
    int cast_rule;
    int target_rule;
};
static const DK2SpellData kDK2Spells[] = {
%s
};
static const unsigned kDK2SpellCount = sizeof(kDK2Spells) / sizeof(kDK2Spells[0]);
""" % "\n".join(rows)

def main():
    stats = json.load(open(os.path.join(DOCS, "stats.json"), encoding="utf-8"))
    triggers = json.load(open(os.path.join(DOCS, "triggers.json"), encoding="utf-8"))
    with open(os.path.join(ENGINE, "CreatureStats.generated.hpp"), "w") as fh:
        fh.write(gen_creatures(stats))
    with open(os.path.join(ENGINE, "MissionRules.generated.hpp"), "w") as fh:
        fh.write(gen_missions(triggers))
    with open(os.path.join(ENGINE, "MissionTriggers.generated.hpp"), "w") as fh:
        fh.write(gen_trigger_data(triggers))
    with open(os.path.join(ENGINE, "SpellData.generated.hpp"), "w") as fh:
        fh.write(gen_spells(stats))
    print("generated %d creature stats, %d mission rules" %
          (len(stats["creatures"]), len(triggers["maps"])))


if __name__ == "__main__":
    main()
