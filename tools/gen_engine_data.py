#!/usr/bin/env python3
"""Generate C++ tables from the recovered original game data.

Inputs:  docs/stats.json, docs/triggers.json, docs/game_data.json
Outputs: engine/CreatureStats.generated.hpp, engine/MissionRules.generated.hpp
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(HERE)
DOCS = os.path.join(PORT, "docs")
ENGINE = os.path.join(PORT, "engine")


def val(entry, key, default=0):
    if not isinstance(entry, dict):
        return default
    item = entry.get(key)
    if isinstance(item, dict):
        return item.get("value", default)
    return item if item is not None else default


def fnum(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) + "f" if isinstance(v, float) else str(v)
    return "0"


def gen_creatures(stats):
    rows = []
    for c in stats["creatures"]:
        s = c.get("stats", {})
        def sane(key, default, hi):
            v = float(val(s, key, default))
            return v if 0.0 <= v <= hi else float(default)
        row = (
            '    {"%s", %d, %.6ff, %.6ff, %.6ff, %.6ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %.1ff, %d},'
            % (
                c["name"].replace('"', ''),
                int(val(s, "hp", 100)),
                float(val(s, "speed", 1.0)),
                float(val(s, "run_speed", val(s, "speed", 1.0))),
                float(val(s, "melee_damage", 10)),
                float(val(s, "melee_recharge", 1.0)),
                sane("fear", 5, 1000),
                sane("threat", 2, 1000),
                sane("melee_range", 1.0, 100),
                sane("distance_can_see", 8.0, 100),
                sane("pay", 0, 100000),
                sane("unhappy_threshold", 50, 100),
                int(val(s, "max_gold_held", 0)),
            )
        )
        rows.append(row)
    return """// Generated by tools/gen_engine_data.py from shipped game data. Do not edit.
#pragma once
struct DK2CreatureStat {
    const char *name;
    int hp;
    float speed;
    float run_speed;
    float melee_damage;
    float melee_recharge;
    float fear;
    float threat;
    float melee_range;
    float sight_range;
    float pay;
    float unhappy_threshold;
    int max_gold_held;
};
static const DK2CreatureStat kDK2CreatureStats[] = {
%s
};
static const unsigned kDK2CreatureStatCount =
    sizeof(kDK2CreatureStats) / sizeof(kDK2CreatureStats[0]);
""" % "\n".join(rows)


def gen_missions(triggers):
    out = []
    for m in triggers["maps"]:
        wl = m.get("win_lose", {})
        requirements = []
        for finding in wl.get("findings", []):
            if finding.get("action") != "WIN_GAME":
                continue
            for cond in finding.get("ancestor_conditions", []):
                t = cond.get("type_name", "")
                p = cond.get("params", {})
                if t.startswith("PLAYER_GOLD"):
                    requirements.append(("gold", float(p.get("value", 0))))
                elif t.startswith("PLAYER_CREATURES"):
                    requirements.append(("creatures", float(p.get("value", 0))))
                elif t.startswith("PLAYER_ROOMS"):
                    requirements.append(("rooms", float(p.get("value", 0))))
                elif t.startswith("TIMER"):
                    requirements.append(("time", float(p.get("value", 0))))
                elif t.startswith("PLAYER_KILLED"):
                    requirements.append(("enemy_killed", 1.0))
        g = max([v for k, v in requirements if k == "gold"] or [0])
        c = max([v for k, v in requirements if k == "creatures"] or [0])
        r = max([v for k, v in requirements if k == "rooms"] or [0])
        t = max([v for k, v in requirements if k == "time"] or [0])
        ek = 1 if any(k == "enemy_killed" for k, _ in requirements) else 0
        out.append('    {"%s", %.1ff, %.1ff, %.1ff, %.1ff, %d},' %
                   (m["name"].replace('"', ''), g, c, r, t, ek))
    return """// Generated by tools/gen_engine_data.py from recovered mission triggers.
#pragma once
struct DK2MissionRule {
    const char *map;
    float required_gold;
    float required_creatures;
    float required_rooms;
    float min_time;
    int enemy_must_die;
};
static const DK2MissionRule kDK2MissionRules[] = {
%s
};
static const unsigned kDK2MissionRuleCount =
    sizeof(kDK2MissionRules) / sizeof(kDK2MissionRules[0]);
""" % "\n".join(out)



# --- trigger generator -------------------------------------------------------
# Order below is the single source of truth for both the emitted C++ struct and
# the Python round-trip self-test. Do not reorder without changing both.
TRIGGER_FIELDS = (
    "id", "is_action", "type", "comparison", "tag", "repeat_times",
    "flag", "value_id", "text_id", "path_id", "action_point_id",
    "root_tag", "player", "target_id", "available", "pos_x", "pos_y",
    "value", "next", "child", "id_param",
)


def _traw(node, key, default=0):
    raw = node.get("param_raw")
    if not isinstance(raw, dict):
        return default
    item = raw.get(key, default)
    return default if item is None else item


def _tint(node, key, default=0):
    try:
        return int(_traw(node, key, default))
    except (TypeError, ValueError):
        return default


def _tfloat(node, key, default=0.0):
    try:
        return float(_traw(node, key, default))
    except (TypeError, ValueError):
        return float(default)


def _trigger_text_id(node):
    """Numeric text reference: text_id/speech_id/objective_id/information_id.

    The u8 ``text`` field of PLAY_SPEECH is a subtitle flag, not an id, and is
    deliberately excluded. DISPLAY_TEXT_STRING (action 25) uses ``text_id``;
    no shipped map has action 25, but the field is kept for completeness.
    """
    raw = node.get("param_raw")
    if not isinstance(raw, dict):
        return 0
    for key in ("text_id", "information_id", "speech_id", "objective_id"):
        if key in raw:
            return _tint(node, key)
    return 0


def _trigger_target_id(node):
    """The value tested by a condition / primary id of an action.

    KwdFile.java:2584-2598 names byte 1 ``targetId``; trigger_tool.py calls the
    same byte ``flag_id`` (FLAG) or ``timer_id`` (TIMER). Both are covered.
    """
    raw = node.get("param_raw")
    if not isinstance(raw, dict):
        return 0
    for key in ("target_id", "flag_id", "timer_id", "creature_id", "room_id",
                "terrain_id", "object_id", "party_id", "player_id"):
        if key in raw:
            return _tint(node, key)
    return 0


def trigger_node_values(node, root_tag):
    raw = node.get("param_raw")
    if not isinstance(raw, dict):
        raw = {}
    if isinstance(root_tag, str):
        root_tag = int(root_tag, 16)
    return {
        "id": int(node.get("id", 0)),
        "is_action": 1 if node.get("kind") == "action" else 0,
        "type": int(node.get("type_id", 0)),
        "comparison": _tint(node, "comparison"),
        "tag": int(node.get("tag", 0)),
        "repeat_times": int(node.get("repeat_times", 0)),
        "flag": _tint(node, "flag"),
        "value_id": _tint(node, "value_id"),
        "text_id": _trigger_text_id(node),
        "path_id": _tint(node, "path_id"),
        "action_point_id": _tint(node, "action_point_id"),
        "root_tag": int(root_tag),
        "player": _tint(node, "player_id"),
        "target_id": _trigger_target_id(node),
        "available": _tint(node, "available"),
        "pos_x": _tint(node, "pos_x"),
        "pos_y": _tint(node, "pos_y"),
        "value": _tfloat(node, "value"),
        "next": int(node.get("next_id", 0)),
        "child": int(node.get("child_id", 0)),
        "id_param": _tint(node, "flag_id") or _tint(node, "timer_id"),
    }


def _trigger_row(values):
    parts = []
    for key in TRIGGER_FIELDS:
        part = values[key]
        parts.append("%.1ff" % part if key == "value" else str(int(part)))
    return "        {" + ",".join(parts) + "},"


GEN_TRIGGER_HEADER = """// Generated by tools/gen_engine_data.py from recovered mission triggers.
// Chain semantics (OpenKeeper TriggerLoader/TriggerControl, HIGH by structure):
//   child = first child; next = next sibling in the SAME parent.
//   0 = no link. 65535 is a REAL action id in shipped maps, not a sentinel.
//   Children are visited in `next` order: the first active condition wins,
//   every action encountered in the list is executed.
#pragma once
struct DK2TriggerNode {
    unsigned id;               // record id; 0 = none
    unsigned char is_action;   // 0 = condition (0xD5), 1 = action (0xD6)
    unsigned char type;        // TargetType / ActionType
    unsigned char comparison;  // 0..6, conditions only
    unsigned char tag;         // 0xD5 condition, 0xD6 action
    unsigned repeat_times;     // 255 = always, 0 = detachable after first use
    unsigned flag;             // 1 = literal value, else indirect flag/timer
    unsigned value_id;         // indirect flag_id / timer_id source
    unsigned text_id;          // speech / objective / information / text id
    unsigned path_id;          // camera path id
    unsigned action_point_id;
    unsigned root_tag;         // file root tag (0xD2)
    unsigned player;           // player_id
    unsigned target_id;        // flag/timer/creature/room/... id being tested
    unsigned available;
    float pos_x;
    float pos_y;
    float value;               // literal comparison / duration value
    unsigned next;             // idNext sibling, 0 = none
    unsigned child;            // idChild, 0 = none
    unsigned id_param;         // legacy alias of flag_id / timer_id
};
struct DK2MissionTriggers {
    const char *map;
    unsigned count;
    const DK2TriggerNode *nodes;
};
static const DK2MissionTriggers kDK2MissionTriggers[] = {
%s
};
static const unsigned kDK2MissionTriggerCount =
    sizeof(kDK2MissionTriggers) / sizeof(kDK2MissionTriggers[0]);

inline const DK2TriggerNode* findDK2TriggerNode(const DK2MissionTriggers& set,
                                                unsigned id) {
    if (id == 0) return nullptr;
    for (unsigned i = 0; i < set.count; ++i)
        if (set.nodes[i].id == id) return &set.nodes[i];
    return nullptr;
}

// Structural check over every generated node. Returns true when the table is
// internally consistent and the shipped-data totals are intact.
inline bool dk2MissionTriggersSelfTest(unsigned* maps, unsigned* nodes,
                                       unsigned* conditions, unsigned* actions) {
    unsigned nmap = 0, nnode = 0, ncond = 0, nact = 0, bad = 0;
    for (unsigned m = 0; m < kDK2MissionTriggerCount; ++m) {
        const DK2MissionTriggers& set = kDK2MissionTriggers[m];
        ++nmap;
        if (!set.map || (!set.nodes && set.count)) { ++bad; continue; }
        if (!set.nodes) continue;  // 6 shipped maps are empty
        for (unsigned i = 0; i < set.count; ++i) {
            const DK2TriggerNode& n = set.nodes[i];
            ++nnode;
            if (n.is_action) ++nact; else ++ncond;
            if (n.id == 0 || findDK2TriggerNode(set, n.id) != &n) ++bad;
            if (n.next && !findDK2TriggerNode(set, n.next)) ++bad;
            if (n.child && !findDK2TriggerNode(set, n.child)) ++bad;
            if (n.comparison > 6 || n.tag != (n.is_action ? 214u : 213u)) ++bad;
            if (n.is_action && n.comparison != 0) ++bad;
            if (n.root_tag != 0xD2u) ++bad;
        }
    }
    if (maps) *maps = nmap;
    if (nodes) *nodes = nnode;
    if (conditions) *conditions = ncond;
    if (actions) *actions = nact;
    return bad == 0 && nmap == 66 && nnode == 9161 && ncond == 3753 && nact == 5408;
}
"""


def gen_trigger_data(triggers):
    out = []
    expected = triggers.get("totals", {})
    counts = {"maps": 0, "nodes": 0, "conditions": 0, "actions": 0}
    for m in triggers["maps"]:
        rows = []
        for n in m.get("nodes", []):
            values = trigger_node_values(n, m.get("root_tag", "0xd2"))
            rows.append(_trigger_row(values))
            counts["nodes"] += 1
            counts["conditions" if not values["is_action"] else "actions"] += 1
        counts["maps"] += 1
        out.append('    {"%s", %d,' % (m["name"].replace('"', ''), len(rows)))
        if rows:
            out.append("     (const DK2TriggerNode[]){")
            out.extend(rows)
            out.append("     }},")
        else:
            out.append("     nullptr},")
    for key in ("maps", "nodes", "conditions", "actions"):
        if key in expected and int(expected[key]) != counts[key]:
            raise ValueError("trigger totals mismatch for %s: %d != %d" %
                             (key, counts[key], int(expected[key])))
    return GEN_TRIGGER_HEADER % "\n".join(out)


def trigger_self_test(triggers):
    """Re-parse the generated C++ rows and compare every field to triggers.json."""
    import re

    header = gen_trigger_data(triggers)
    maps, current = [], None
    header_re = re.compile(r'^\s*\{"((?:[^"\\]|\\.)*)",\s*(\d+),\s*$')
    row_re = re.compile(r'^\s*\{([^{}]*)\},\s*$')
    for line in header.splitlines():
        match = header_re.match(line)
        if match:
            current = {"name": match.group(1), "count": int(match.group(2)), "rows": []}
            maps.append(current)
            continue
        match = row_re.match(line)
        if match and current is not None:
            current["rows"].append([t.strip() for t in match.group(1).split(",")])

    errors = []
    totals = {"maps": len(maps), "nodes": 0, "conditions": 0, "actions": 0}
    sources = triggers["maps"]
    if len(maps) != len(sources):
        errors.append("map count %d != %d" % (len(maps), len(sources)))
    for src, got in zip(sources, maps):
        expected_name = src["name"].replace('"', '')
        if got["name"] != expected_name:
            errors.append("map name %r != %r" % (got["name"], expected_name))
        nodes = src.get("nodes", [])
        if got["count"] != len(nodes):
            errors.append("%s: count %d != %d" % (expected_name, got["count"], len(nodes)))
        if len(got["rows"]) != len(nodes):
            errors.append("%s: rows %d != %d" % (expected_name, len(got["rows"]), len(nodes)))
        for index, (node, row) in enumerate(zip(nodes, got["rows"])):
            totals["nodes"] += 1
            want = trigger_node_values(node, src.get("root_tag", "0xd2"))
            totals["actions" if want["is_action"] else "conditions"] += 1
            if len(row) != len(TRIGGER_FIELDS):
                errors.append("%s/%d: %d fields != %d" %
                              (expected_name, index, len(row), len(TRIGGER_FIELDS)))
                continue
            for key, token in zip(TRIGGER_FIELDS, row):
                try:
                    actual = float(token[:-1]) if key == "value" else int(token)
                except ValueError:
                    errors.append("%s/%d.%s: unparsable %r" %
                                  (expected_name, index, key, token))
                    continue
                if actual != want[key] and not (key == "value" and abs(actual - want[key]) < 1e-6):
                    errors.append("%s/%d.%s: %r != %r" %
                                  (expected_name, index, key, actual, want[key]))

    expected = triggers.get("totals", {})
    for key, value in totals.items():
        if key in expected and int(expected[key]) != value:
            errors.append("total %s: %d != %d" % (key, value, int(expected[key])))
    print("trigger round-trip: %(maps)d maps, %(nodes)d nodes "
          "(%(conditions)d conditions / %(actions)d actions)" % totals)
    if errors:
        for err in errors[:20]:
            print("  ERROR: " + err)
        if len(errors) > 20:
            print("  ... %d more" % (len(errors) - 20))
        return False
    print("trigger round-trip: OK (all fields match docs/triggers.json)")
    return True


def gen_spells(stats):
    rows = []
    for sp in stats["keeper_spells"]:
        st = sp.get("stats", {})
        rows.append('    {"%s", %d, %d, %.1ff, %.1ff, %d, %d, %d},' % (
            sp["name"].replace('"', ''),
            int(val(st, "keeper_spell_id", 0)),
            int(val(st, "mana_cost", 0)),
            float(val(st, "research_time", 0)),
            float(val(st, "recharge_time", 0)),
            int(val(st, "cast_rule", 0)),
            int(val(st, "target_rule", 0)),
            int(val(st, "flags", 0)),
        ))
    return """// Generated by tools/gen_engine_data.py from KeeperSpells.kwd.
#pragma once
struct DK2SpellData {
    const char *name;
    int id;
    int mana_cost;
    float research_time;
    float recharge_time;
    int cast_rule;
    int target_rule;
    int flags;
};
static const DK2SpellData kDK2Spells[] = {
%s
};
static const unsigned kDK2SpellCount = sizeof(kDK2Spells) / sizeof(kDK2Spells[0]);
""" % "\n".join(rows)

def main():
    stats = json.load(open(os.path.join(DOCS, "stats.json"), encoding="utf-8"))
    triggers = json.load(open(os.path.join(DOCS, "triggers.json"), encoding="utf-8"))
    if "--self-test" in sys.argv:
        if not trigger_self_test(triggers):
            raise SystemExit(1)
        return
    with open(os.path.join(ENGINE, "CreatureStats.generated.hpp"), "w") as fh:
        fh.write(gen_creatures(stats))
    with open(os.path.join(ENGINE, "MissionRules.generated.hpp"), "w") as fh:
        fh.write(gen_missions(triggers))
    with open(os.path.join(ENGINE, "MissionTriggers.generated.hpp"), "w") as fh:
        fh.write(gen_trigger_data(triggers))
    with open(os.path.join(ENGINE, "SpellData.generated.hpp"), "w") as fh:
        fh.write(gen_spells(stats))
    print("generated %d creature stats, %d mission rules" %
          (len(stats["creatures"]), len(triggers["maps"])))


if __name__ == "__main__":
    main()
